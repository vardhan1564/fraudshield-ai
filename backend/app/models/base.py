"""Declarative base shared by every table (spec 05): UUID v4 ids and `created_at`."""

import uuid
from datetime import datetime
from decimal import Decimal
from typing import Any

from sqlalchemy import REAL, DateTime, MetaData, Numeric, func, text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Stable constraint names, so Alembic migrations can refer to them later.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

Money = Numeric(14, 2)


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    type_annotation_map = {
        datetime: DateTime(timezone=True),
        dict[str, Any]: JSONB,
        list[Any]: JSONB,
        Decimal: Money,
        float: REAL,  # spec 05 scores are `real`
    }

    created_at: Mapped[datetime] = mapped_column(server_default=func.now())


class UUIDPk:
    """`id uuid PK`, generated by the app and by Postgres (for rows inserted in plain SQL)."""

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True, default=uuid.uuid4, server_default=text("gen_random_uuid()")
    )
